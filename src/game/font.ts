export const GLYPH_W = 5;
export const GLYPH_H = 7;
/** 1px gap between glyphs. */
export const ADVANCE = GLYPH_W + 1;

/** Width in pixels of a string rendered at 1x. */
export const textWidth = (s: string): number => (s.length ? s.length * ADVANCE - 1 : 0);

type Plot = (x: number, y: number) => void;

/**
 * Draw uppercase ASCII at integer pixel coordinates. Anything not in the table
 * renders as a blank cell rather than throwing — a missing glyph should never
 * be able to take down the world screen.
 */
export function drawText(text: string, x: number, y: number, plot: Plot): void {
  const upper = text.toUpperCase();
  for (let i = 0; i < upper.length; i++) {
    const rows = GLYPHS[upper[i]];
    if (!rows) continue;
    const gx = x + i * ADVANCE;
    for (let r = 0; r < GLYPH_H; r++) {
      const row = rows[r];
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === "1") plot(gx + c, y + r);
      }
    }
  }
}

/** True if every glyph in `text` exists in the table. */
export const isRenderable = (text: string): boolean =>
  [...text.toUpperCase()].every((ch) => ch in GLYPHS);
